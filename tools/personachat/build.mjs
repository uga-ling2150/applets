// Builds docs/week_11/11c/dialogues.js for Activity 11C from the PersonaChat mirror on Hugging Face.
// Each row of that dataset holds only ONE persona: the speaker who gives the final reply. The train
// split stores every dialogue twice, once from each side: row i is the responder's view and row
// i + HALF is the opener's view (its history starts with "__ SILENCE __"). Pairing the two gives
// both persona lists for one conversation.
//
//   node tools/personachat/build.mjs [count]     (default 200 conversations)
import { writeFile } from 'node:fs/promises';

const DATASET = 'AlekseyKorshuk/persona-chat';
const HALF = 8939;
const COUNT = Number(process.argv[2] || 200);
const OUT = new URL('../../docs/week_11/11c/dialogues.js', import.meta.url);
// Responder row numbers left out for the classroom. 17: a persona line about a suicide pact.
const EXCLUDE = new Set([17]);

async function rows(offset, length) {
  const out = [];
  for (let start = offset; start < offset + length; start += 100) {
    const url = `https://datasets-server.huggingface.co/rows?dataset=${encodeURIComponent(DATASET)}&config=default&split=train&offset=${start}&length=${Math.min(100, offset + length - start)}`;
    const response = await fetch(url);
    if (!response.ok) throw Error(`${response.status} for ${url}`);
    out.push(...(await response.json()).rows.map(r => r.row));
  }
  return out;
}

// The whole conversation a row can see: its history plus the gold reply (the last candidate).
const transcript = row => { const last = row.utterances.at(-1); return [...last.history, last.candidates.at(-1)]; };

const responders = await rows(0, COUNT), openers = await rows(HALF, COUNT);
const dialogues = [];
for (let i = 0; i < COUNT; i++) {
  if (EXCLUDE.has(i)) continue;
  const b = transcript(responders[i]), a = transcript(openers[i]);
  if (a[0] !== '__ SILENCE __') { console.warn(`skip ${i}: opener row has no SILENCE marker`); continue; }
  const fromA = a.slice(1);
  // One view may be missing the other speaker's final line; keep the longer and check they agree.
  const [long, short] = fromA.length >= b.length ? [fromA, b] : [b, fromA];
  if (short.some((line, k) => line !== long[k])) { console.warn(`skip ${i}: the two views disagree`); continue; }
  dialogues.push({ rows: [HALF + i, i], a: openers[i].personality, b: responders[i].personality, turns: long });
}

const banner = `/* GENERATED by tools/personachat/build.mjs from ${DATASET} (train split). Do not edit by hand.
   Speaker A opens each conversation; A's persona is from row rows[0], B's from row rows[1]. */`;
const body = `(function (root, data) {
  if (typeof module === 'object' && module.exports) module.exports = data;
  else root.PersonaChatData = data;
})(typeof self !== 'undefined' ? self : this, ${JSON.stringify({ source: DATASET, split: 'train', dialogues })});
`;
await writeFile(OUT, `${banner}\n${body}`);
console.log(`Wrote ${dialogues.length} of ${COUNT} conversations to ${OUT.pathname}`);
