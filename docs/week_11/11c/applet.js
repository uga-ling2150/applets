/* 11C PersonaChat reader: pick a conversation, show both personas above it. The data is in
   dialogues.js (generated by tools/personachat/build.mjs). The open conversation is kept in the
   URL hash (#12), so a group can share the same one by link. */
(() => {
  'use strict';
  const $ = id => document.getElementById(id);
  const dialogues = window.PersonaChatData.dialogues, total = dialogues.length;
  const speaker = ['A', 'B'];
  let current = 0;

  function fill(list, facts) {
    list.replaceChildren(...facts.map(fact => { const li = document.createElement('li'); li.textContent = fact; return li; }));
  }

  function show(index) {
    current = (index + total) % total;
    const d = dialogues[current], number = current + 1;
    fill($('persona-a'), d.a);
    fill($('persona-b'), d.b);
    $('log').replaceChildren(...d.turns.map((text, k) => {
      const li = document.createElement('li'), who = document.createElement('span'), body = document.createElement('p');
      li.className = 'chat-turn ' + (k % 2 ? 'ai' : 'human');
      who.className = 'chat-turn__speaker'; who.textContent = `${k + 1}. Speaker ${speaker[k % 2]}`;
      body.className = 'chat-turn__text'; body.textContent = text;
      li.append(who, body);
      return li;
    }));
    $('log').scrollTop = 0;
    $('number').value = number;
    $('source-rows').textContent = `Dataset rows ${d.rows[0]} (Speaker A) and ${d.rows[1]} (Speaker B), ${d.turns.length} turns.`;
    $('reader-status').textContent = `Conversation ${number} of ${total} loaded: ${d.turns.length} turns.`;
    if (location.hash !== '#' + number) history.replaceState(null, '', '#' + number);
  }

  const fromHash = () => { const n = parseInt(location.hash.slice(1), 10); return n >= 1 && n <= total ? n - 1 : 0; };

  $('number').max = total;
  $('number-total').textContent = `of ${total}`;
  $('picker').addEventListener('submit', event => {
    event.preventDefault();  // min/max/step on the input mean only 1..total gets this far
    show(Number($('number').value) - 1);
  });
  $('prev').addEventListener('click', () => show(current - 1));
  $('next').addEventListener('click', () => show(current + 1));
  $('random').addEventListener('click', () => show((current + 1 + Math.floor(Math.random() * (total - 1))) % total));
  addEventListener('hashchange', () => show(fromHash()));
  show(fromHash());
})();
